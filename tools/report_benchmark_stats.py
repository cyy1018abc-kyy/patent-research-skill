#!/usr/bin/env python3
"""Benchmark stats single-source generator (blueprint T-06).

Reads archived score reports (``benchmarks/retrieval/results/*.json`` produced by
``tools/score_retrieval.py``) and emits ONE markdown table that README/CHANGELOG
must quote verbatim — hand-written statistics in docs are the failure mode this
tool exists to prevent.

Usage:
    python tools/report_benchmark_stats.py --results benchmarks/retrieval/results --out build/benchmark-stats.md
    python tools/report_benchmark_stats.py --results ... --check <file>   # verify a doc matches
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

EXIT_OK = 0
EXIT_FAIL = 1
EXIT_USAGE = 2


def load_reports(results_dir: Path) -> list[dict[str, Any]]:
    reports: list[dict[str, Any]] = []
    for path in sorted(results_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            print(f"[FATAL] {path}: invalid JSON: {exc}", file=sys.stderr)
            raise SystemExit(EXIT_FAIL) from None
        if not isinstance(data, dict) or data.get("tool") != "score_retrieval":
            continue  # not a score report (manifest backups etc.)
        for key in ("suite", "version", "qrels_version", "recall_at_k", "mrr", "topics_evaluated"):
            if key not in data:
                print(f"[FATAL] {path}: missing '{key}' — not a complete score report", file=sys.stderr)
                raise SystemExit(EXIT_FAIL)
        data["_source"] = path.name
        reports.append(data)
    return reports


def render(reports: list[dict[str, Any]]) -> str:
    """One deterministic markdown table. Regenerated on every run; never hand-edited."""
    lines = [
        "<!-- AUTO-GENERATED by tools/report_benchmark_stats.py — do not edit by hand -->",
        "<!-- Source of truth: benchmarks/retrieval/results/*.json (score_retrieval.py output) -->",
        "",
        "| suite | qrels | topics | Recall@50 | Recall@100 | Recall@200 | MRR | critical recall | report |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for report in sorted(reports, key=lambda r: (r["suite"], r["version"], r["_source"])):
        recall = report.get("recall_at_k", {})
        cr = report.get("critical_recall") or {}
        lines.append(
            "| {suite} v{version} | {qrels} | {topics} | {r50:.4f} | {r100:.4f} | {r200:.4f} | {mrr:.4f} | {crit} | {src} |".format(
                suite=report["suite"],
                version=report["version"],
                qrels=report["qrels_version"],
                topics=report["topics_evaluated"],
                r50=float(recall.get("50", 0.0)),
                r100=float(recall.get("100", 0.0)),
                r200=float(recall.get("200", 0.0)),
                mrr=float(report.get("mrr", 0.0)),
                crit=(f"{float(cr['value']):.4f} (n={cr.get('n_topics', 0)})" if cr.get("n_topics") else "n/a"),
                src=str(report.get("_source", "")),
            )
        )
    if not reports:
        lines.append("| (no archived reports) | | | | | | | | |")
    lines.append("")
    lines.append(
        "_Numbers describe the archived evaluation runs only. Claims about recall "
        "improvement follow docs/retrieval-evaluation.md §4 gates._"
    )
    return "\n".join(lines) + "\n"


def _pin_utf8_stdio() -> None:
    # The AUTO-GENERATED banner carries an em-dash; without pinning, cp1252 CI
    # runners emitted 0x97 and every UTF-8 consumer of this tool's output died.
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            try:
                reconfigure(encoding="utf-8", errors="replace")
            except (ValueError, OSError):
                pass


def main(argv: list[str] | None = None) -> int:
    _pin_utf8_stdio()
    parser = argparse.ArgumentParser(prog="report_benchmark_stats")
    parser.add_argument("--results", required=True, metavar="DIR", help="directory of archived score reports")
    parser.add_argument("--out", metavar="FILE", help="write the markdown fragment here")
    parser.add_argument("--check", metavar="FILE", help="verify an existing doc contains exactly this fragment")
    args = parser.parse_args(argv)

    results_dir = Path(args.results)
    if not results_dir.is_dir():
        print(f"[FATAL] results dir missing: {results_dir}", file=sys.stderr)
        return EXIT_USAGE
    reports = load_reports(results_dir)
    fragment = render(reports)

    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(fragment, encoding="utf-8", newline="\n")
        print(f"wrote {out} ({len(reports)} report(s))")
    else:
        print(fragment, end="")

    if args.check:
        target = Path(args.check)
        if not target.is_file():
            print(f"[FATAL] --check target missing: {target}", file=sys.stderr)
            return EXIT_FAIL
        doc = target.read_text(encoding="utf-8")
        body = fragment.splitlines()[3:]  # skip the auto-generated comment header
        missing = [line for line in body if line.strip() and line not in doc]
        if missing:
            print("[FATAL] doc statistics are stale; regenerate with --out and re-embed:", file=sys.stderr)
            for line in missing[:5]:
                print(f"  {line}", file=sys.stderr)
            return EXIT_FAIL
        print(f"[OK] {target} matches the generated statistics")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
