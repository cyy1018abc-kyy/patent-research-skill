"""Versioned data records exchanged across the patent_intel work packages.

Contracts doc: ``docs/architecture/contracts.md``. Rules encoded here:

* every serialized record carries ``schema_version``, ``record_type``, ``owner``
  (owning work package) and ``created_at`` (ISO-8601 UTC) — provenance is part of the
  shape, not an afterthought;
* ``from_dict`` validates types of known fields, refuses records whose *major* schema
  version is newer than this build understands, and preserves unknown fields verbatim
  so older writers keep round-tripping through newer readers;
* enumerations are plain strings (JSON-native) validated against closed sets.

These types are data carriers only. Nothing here interprets evidence levels or legal
meaning — that stays with the kernel (`patentkit`).
"""

