# ── Record framework ──────────────────────────────────────────────────


def _check_type(name: str, value: Any, expected: type) -> None:
    """Validate one field against its declared JSON type (bool before int: bool is an int subclass)."""
    if expected is bool:
        ok = isinstance(value, bool)
    elif expected is int:
        ok = isinstance(value, int) and not isinstance(value, bool)
    elif expected is float:
        ok = isinstance(value, (int, float)) and not isinstance(value, bool)
    elif expected is str:
        ok = isinstance(value, str)
    elif expected is list:
        ok = isinstance(value, list)
    elif expected is dict:
        ok = isinstance(value, dict)
    else:  # pragma: no cover - framework misuse, fail loudly in tests
        raise AssertionError(f"unsupported field type for {name}: {expected!r}")
    if not ok:
        raise RecordValidationError(
            f"field {name!r} must be {expected.__name__}, got {type(value).__name__}: {value!r}"
        )


@dataclass(kw_only=True)
class Record:
    """Base class for all versioned records.

    Subclasses declare ``SPEC`` (field name → JSON type) and ``REQUIRED``. Fields not in
    ``SPEC`` are preserved verbatim in ``extra`` so forward-compatible readers never drop
    data written by newer writers of the *same* schema major.
    """

    SPEC: ClassVar[Mapping[str, type]] = {}
    REQUIRED: ClassVar[tuple[str, ...]] = ()

    owner: str
    created_at: str = field(default_factory=utc_now_iso)
    extra: dict[str, Any] = field(default_factory=dict)

    RECORD_TYPE: ClassVar[str] = "record"

    def __post_init__(self) -> None:
        """Records validate themselves on construction — an invalid record cannot exist."""
        self.validate()

    # -- serialization -------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {
            "schema_version": SCHEMA_VERSION,
            "record_type": self.RECORD_TYPE,
            "owner": self.owner,
            "created_at": self.created_at,
        }
        for name in self.SPEC:
            value = getattr(self, name)
            if value is not None:
                out[name] = value
        out.update(self.extra)
        return out

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "Record":
        if not isinstance(data, Mapping):
            raise RecordValidationError(f"{cls.__name__} expects a JSON object, got {type(data).__name__}")
        version = data.get("schema_version")
        if not isinstance(version, int) or isinstance(version, bool):
            raise RecordValidationError("missing or non-integer 'schema_version'")
        if version != SCHEMA_VERSION:
            raise UnsupportedSchemaError(
                f"record schema_version {version} is not supported by this build (understands {SCHEMA_VERSION})"
            )
        record_type = data.get("record_type")
        if record_type != cls.RECORD_TYPE:
            raise RecordValidationError(
                f"record_type mismatch: expected {cls.RECORD_TYPE!r}, got {record_type!r}"
            )
        owner = data.get("owner")
        if not isinstance(owner, str) or not owner:
            raise RecordValidationError("missing or empty 'owner' (owning work package)")
        for name in cls.REQUIRED:
            if name not in data:
                raise RecordValidationError(f"{cls.RECORD_TYPE} missing required field {name!r}")
        known: dict[str, Any] = {}
        for name, expected in cls.SPEC.items():
            if name in data and data[name] is not None:
                _check_type(name, data[name], expected)
                known[name] = data[name]
        known["owner"] = owner
        created_at = data.get("created_at")
        if created_at is not None:
            _check_type("created_at", created_at, str)
            if not _ISO_TS.match(created_at):
                raise RecordValidationError(f"'created_at' is not ISO-8601 UTC: {created_at!r}")
            known["created_at"] = created_at
        extra = {k: v for k, v in data.items() if k not in cls.SPEC and k not in _FRAMEWORK_KEYS}
        return cls(**known, extra=extra)

    def validate(self) -> None:
        """Semantic checks beyond field types; subclasses override and call super()."""
        for name in self.REQUIRED:
            if getattr(self, name) is None:
                raise RecordValidationError(f"{self.RECORD_TYPE} required field {name!r} is missing")


_FRAMEWORK_KEYS = frozenset({"schema_version", "record_type", "owner", "created_at"})


# ── Concrete records (blueprint §3.1) ─────────────────────────────────


@dataclass(kw_only=True)
class FeatureSpec(Record):
    """One technical feature extracted for the query view (WP-A).

    The *authoritative* feature definition stays in Discovery/patentkit; this is the
    extension's query view and every field must trace back to ``source_refs``.
    """

    RECORD_TYPE = "feature_spec"
    SPEC = {
        "feature_id": str,
        "statement": str,
        "source_refs": list,
        "requiredness": str,
        "negation": bool,
        "approved": bool,
        "axis_id": str,
        "numeric_bounds": list,
    }
    REQUIRED = ("feature_id", "statement", "source_refs", "requiredness")

    feature_id: str
    statement: str
    source_refs: list[str]
    requiredness: str
    negation: bool = False
    approved: bool = False
    axis_id: str | None = None
    numeric_bounds: list[dict[str, Any]] | None = None

    def validate(self) -> None:
        super().validate()
        if self.requiredness not in Requiredness.ALL:
            raise RecordValidationError(
                f"requiredness {self.requiredness!r} not in {Requiredness.ALL}"
            )
        if self.requiredness == Requiredness.NEGATION and not self.negation:
            raise RecordValidationError("requiredness=negation requires negation=true")
        if not self.source_refs:
            raise RecordValidationError("feature must carry at least one source_ref")


@dataclass(kw_only=True)
class QuerySpec(Record):
    """One planned query — always a proposal until a human approves it (WP-A).

    ``feature_ids`` is the *authoritative* technical-feature dimension for coverage
    accounting (adaptive roadmap Task 1): coverage is counted per feature id, never
    per axis id or per query type. ``axis_id`` stays the planning axis. Planners must
    fill ``feature_ids`` whenever the query targets known features; a query with no
    resolvable feature (e.g. an expansion term with unknown origin) keeps it ``None``
    — an empty feature dimension is reported as unknown coverage, never as zero.
    """

    RECORD_TYPE = "query_spec"
    SPEC = {
        "query_id": str,
        "axis_id": str,
        "terms": list,
        "language": str,
        "query_type": str,
        "source": str,
        "feature_ids": list,
        "filters": dict,
        "provenance": list,
        "approved": bool,
        "rendered": dict,
    }
    REQUIRED = ("query_id", "axis_id", "terms", "language", "query_type", "source")

    query_id: str
    axis_id: str
    terms: list[str]
    language: str
    query_type: str
    source: str
    feature_ids: list[str] | None = None
    filters: dict[str, Any] | None = None
    provenance: list[dict[str, Any]] | None = None
    approved: bool = False
    rendered: dict[str, str] | None = None

    def validate(self) -> None:
        super().validate()
        if self.query_type not in QueryType.ALL:
            raise RecordValidationError(f"query_type {self.query_type!r} not in {QueryType.ALL}")
        if not self.terms:
            raise RecordValidationError("query must carry at least one term")
        for term in self.terms:
            if not isinstance(term, str) or not term.strip():
                raise RecordValidationError("query terms must be non-empty strings")
        if self.feature_ids is not None:
            seen: set[str] = set()
            for feature_id in self.feature_ids:
                if not isinstance(feature_id, str) or not feature_id.strip():
                    raise RecordValidationError("query feature_ids must be non-empty strings")
                if feature_id in seen:
                    raise RecordValidationError(
                        f"query feature_ids must be unique; duplicated {feature_id!r}"
                    )
                seen.add(feature_id)
        for item in self.provenance or ():
            if not isinstance(item, dict) or "feature_id" not in item:
                raise RecordValidationError(
                    "every provenance item must be an object with feature_id (UT-Q03)"
                )


@dataclass(kw_only=True)
class SearchRun(Record):
    """One execution of a query against one source (WP-B)."""

    RECORD_TYPE = "search_run"
    SPEC = {
        "run_id": str,
        "query_id": str,
        "source": str,
        "executed_at": str,
        "request_fingerprint": str,
        "hits_reported": int,
        "records_fetched": int,
        "complete": bool,
        "status": str,
        "artifact_refs": list,
        "error": str,
        "incomplete_reason": str,
    }
    REQUIRED = ("run_id", "query_id", "source", "executed_at", "status")

    run_id: str
    query_id: str
    source: str
    executed_at: str
    status: str
    request_fingerprint: str | None = None
    hits_reported: int | None = None
    records_fetched: int | None = None
    complete: bool | None = None
    artifact_refs: list[dict[str, Any]] | None = None
    error: str | None = None
    incomplete_reason: str | None = None

    def validate(self) -> None:
        super().validate()
        if self.status not in RunStatus.ALL:
            raise RecordValidationError(f"status {self.status!r} not in {RunStatus.ALL}")
        for name in ("hits_reported", "records_fetched"):
            value = getattr(self, name)
            if value is not None and value < 0:
                raise RecordValidationError(f"{name} must be >= 0")
        if self.status in (RunStatus.PARTIAL, RunStatus.COMPLETE) and self.complete is None:
            raise RecordValidationError(f"status={self.status} requires an explicit 'complete' flag")
        if self.complete is False and not self.incomplete_reason:
            raise RecordValidationError(
                "complete=false requires incomplete_reason (interface rule 3: reason=unknown/limited/...)"
            )
        if self.status == RunStatus.FAILED and not self.error:
            raise RecordValidationError("status=failed requires 'error'")


@dataclass(kw_only=True)
class RawArtifactRef(Record):
    """Pointer to one captured raw response artifact (WP-B)."""

    RECORD_TYPE = "raw_artifact_ref"
    SPEC = {
        "path": str,
        "sha256": str,
        "mime": str,
        "bytes": int,
        "source": str,
        "captured_at": str,
        "source_record_id": str,
    }
    REQUIRED = ("path", "sha256", "mime", "bytes", "source", "captured_at")

    path: str
    sha256: str
    mime: str
    bytes: int
    source: str
    captured_at: str
    source_record_id: str | None = None

    def validate(self) -> None:
        super().validate()
        if self.bytes < 0:
            raise RecordValidationError("bytes must be >= 0")
        if not re.fullmatch(r"[0-9a-f]{64}", self.sha256):
            raise RecordValidationError(f"sha256 must be 64 lowercase hex chars, got {self.sha256!r}")


@dataclass(kw_only=True)
class PatentRecord(Record):
    """Normalized bibliographic index entry (WP-B). Not an ownership or family judgement."""

    RECORD_TYPE = "patent_record"
    SPEC = {
        "publication_number": str,
        "application_number": str,
        "family_refs": list,
        "priority_dates": list,
        "publication_date": str,
        "source_refs": list,
        "identifier_confidence": str,
        "title": str,
        "assignee": str,
    }
    REQUIRED = ("publication_number", "source_refs", "identifier_confidence")

    publication_number: str
    source_refs: list[dict[str, Any]]
    identifier_confidence: str
    application_number: str | None = None
    family_refs: list[dict[str, Any]] | None = None
    priority_dates: list[str] | None = None
    publication_date: str | None = None
    title: str | None = None
    assignee: str | None = None

    def validate(self) -> None:
        super().validate()
        if self.identifier_confidence not in IdentifierConfidence.ALL:
            raise RecordValidationError(
                f"identifier_confidence {self.identifier_confidence!r} not in {IdentifierConfidence.ALL}"
            )
        if not self.source_refs:
            raise RecordValidationError("patent record must carry at least one source_ref")
        for ref in self.source_refs:
            if not isinstance(ref, dict) or "source" not in ref or "raw_ref" not in ref:
                raise RecordValidationError(
                    "each source_ref needs {source, raw_ref} so candidates stay traceable (interface rule 4)"
                )


@dataclass(kw_only=True)
class DocumentAnchor(Record):
    """A traceable location inside a captured document (WP-C; interface rule 6)."""

    RECORD_TYPE = "document_anchor"
    SPEC = {
        "raw_sha256": str,
        "source_document": str,
        "page": int,
        "bbox": list,
        "paragraph": str,
        "text_hash": str,
        "parser_version": str,
        "verification_status": str,
    }
    REQUIRED = ("raw_sha256", "source_document", "paragraph", "text_hash", "parser_version", "verification_status")

    raw_sha256: str
    source_document: str
    paragraph: str
    text_hash: str
    parser_version: str
    verification_status: str
    page: int | None = None
    bbox: list[float] | None = None

    def validate(self) -> None:
        super().validate()
        if not re.fullmatch(r"[0-9a-f]{64}", self.raw_sha256):
            raise RecordValidationError("raw_sha256 must be 64 lowercase hex chars")
        if not re.fullmatch(r"[0-9a-f]{64}", self.text_hash):
            raise RecordValidationError("text_hash must be 64 lowercase hex chars")
        if self.verification_status not in AnchorVerification.ALL:
            raise RecordValidationError(
                f"verification_status {self.verification_status!r} not in {AnchorVerification.ALL}"
            )
        if self.page is not None and self.page < 1:
            raise RecordValidationError("page is 1-based")
        if self.bbox is not None and len(self.bbox) not in (0, 4):
            raise RecordValidationError("bbox must be [x0, y0, x1, y1]")


