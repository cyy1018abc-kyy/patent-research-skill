#!/usr/bin/env python
"""Generate the comparison run skeleton under `04_comparative_analysis/runs/` — thin wrapper over `patentkit.api.report`.

The skeleton content (D column, N-main-axis coverage matrix, three-tier determination placeholders, and
the `capture_mode` metadata section) is generated by `patentkit/report.py`; this script only locates the
workspace, resolves relative paths against the workspace root, and collapses failures into exit codes.

Usage:

    # Write to a relative path inside the workspace (--out is resolved against the workspace root, not the current directory)
    python patent-research-skill/scripts/report.py --target TGT-0002 \
        --out 04_comparative_analysis/runs/2026-01-01_TGT-0002.md

    # No write; print the skeleton to stdout for preview
    python patent-research-skill/scripts/report.py --target TGT-0002

Exit code: 0 generated / 1 generation or write failure / 2 workspace problem or usage error / 3 missing dependency.

⚠️ Why `--out` has no default: writing to disk by default would pollute workspace data before the user has
thought it through. This script **would rather make you type one extra argument** than guess a path for you.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import _env


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="report.py",
        description="Generate the comparison run skeleton (thin wrapper over patentkit.api.report)",
    )
    parser.add_argument(
        "--target",
        metavar="TGT-xxxx",
        required=True,
        help="target ID; must match an entry in targets of 00_methodology/glossary.yml, otherwise the skeleton has no axes",
    )
    parser.add_argument(
        "--out",
        metavar="PATH",
        default=None,
        help="output path; a relative path is resolved against the workspace root. Omit it to print the skeleton only (no write)",
    )
    _env.add_common_args(parser)
    return parser


def _resolve_out(root: Path, raw: str | None) -> Path | None:
    """A relative `--out` path is resolved against the **workspace root**, not the current directory.

    Skill scripts are often invoked by clients from an arbitrary cwd; resolving against cwd would drop
    files in unexpected places.
    """
    if not raw:
        return None
    out = Path(raw).expanduser()
    if not out.is_absolute():
        out = root / out
    return out


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    _env.require_patentkit()
    root = _env.resolve_workspace(args.root, as_json=args.json)
    out = _resolve_out(root, args.out)

    # Deferred import: when the package is missing, require_patentkit() gives install guidance instead of a traceback
    from patentkit import api
    from patentkit.registry import TerminologyError

    extra = ["--out", str(out)] if out is not None else []
    try:
        data = api.report(root, target=args.target, argv_extra=extra)
    except (api.WorkspaceError, TerminologyError) as exc:
        return _env.failure(
            f"Failed to read workspace data: {exc}",
            _env.EXIT_WORKSPACE,
            hints=("Run python -m patentkit doctor first to locate whether the glossary or a data file is the problem",),
            as_json=args.json,
        )
    except OSError as exc:
        return _env.failure(
            f"Failed to write the comparison run skeleton: {exc}",
            _env.EXIT_FAIL,
            hints=("--out must be a writable file path (it cannot be an existing directory)",),
            as_json=args.json,
        )

    if not data.get("ok"):
        detail = data.get("stderr") or data.get("stdout") or "(the underlying layer produced no output)"
        return _env.failure(
            f"Failed to generate the comparison run skeleton: {detail}",
            _env.EXIT_FAIL,
            as_json=args.json,
        )

    if args.json:
        _env.emit_json(
            {
                **data,
                "command": "report",
                "workspace": str(root),
                "target": args.target,
                "out": str(out) if out is not None else None,
            }
        )
        return _env.EXIT_OK

    if out is not None:
        print(f"✅ Comparison run skeleton generated: {out}")
        print(f"   Target: {args.target}")
        print(
            "   Next steps: fill in the §3 coverage matrix and the §4 three-tier determination; "
            "the §6 capture_mode must be tagged truthfully"
        )
        print("           (live → may qualify as verified; retrospective / memory → asserted only)")
    else:
        # Preview mode: the underlying layer prints the skeleton to captured stdout; forward it verbatim
        print(data.get("stdout") or "")
    return _env.EXIT_OK


if __name__ == "__main__":
    raise SystemExit(_env.run_script(main))
